package com.javaee.aiservice.review.m0.baseline;

import org.junit.jupiter.api.Assertions;

import javax.tools.Diagnostic;
import javax.tools.DiagnosticCollector;
import javax.tools.JavaCompiler;
import javax.tools.JavaFileObject;
import javax.tools.StandardJavaFileManager;
import javax.tools.ToolProvider;
import java.io.File;
import java.io.ByteArrayInputStream;
import java.io.InputStream;
import java.lang.reflect.InvocationTargetException;
import java.lang.reflect.Method;
import java.net.URL;
import java.net.URLClassLoader;
import java.nio.charset.StandardCharsets;
import java.nio.file.Files;
import java.nio.file.Path;
import java.util.ArrayList;
import java.util.List;
import java.util.Locale;

/**
 * Compiles and loads the checked-in document-service parser without copying it
 * into ai-service or changing either module's dependencies. The classpath file
 * is generated by the documented Maven baseline command.
 */
final class ProductionDocumentParserHarness implements AutoCloseable {

    private static final String PARSER_CLASS = "com.javaee.documentservice.util.DocumentParserUtil";
    private static final String PARSER_SOURCE =
            "document-service/src/main/java/com/javaee/documentservice/util/DocumentParserUtil.java";
    private static final String DEFAULT_CLASSPATH_FILE =
            "document-service/target/m0-pb-runtime-classpath.txt";

    private final URLClassLoader classLoader;
    private final Method parseDocument;
    private final Method isSupportedDocument;

    private ProductionDocumentParserHarness(
            URLClassLoader classLoader,
            Method parseDocument,
            Method isSupportedDocument
    ) {
        this.classLoader = classLoader;
        this.parseDocument = parseDocument;
        this.isSupportedDocument = isSupportedDocument;
    }

    static ProductionDocumentParserHarness compileFromProductionSource(Path compiledClasses) throws Exception {
        Path repositoryRoot = repositoryRoot();
        Path source = repositoryRoot.resolve(PARSER_SOURCE);
        String configuredClasspath = System.getProperty("omnidoc.m0.parserClasspath", "").trim();
        Path classpathFile = configuredClasspath.isEmpty()
                ? repositoryRoot.resolve(DEFAULT_CLASSPATH_FILE)
                : Path.of(configuredClasspath).toAbsolutePath().normalize();

        Assertions.assertTrue(Files.isRegularFile(source), "Production parser source is missing: " + source);
        Assertions.assertTrue(Files.isRegularFile(classpathFile), () -> """
                document-service dependency classpath is missing: %s
                Run the documented dependency:build-classpath command before the M0-PB tests.
                """.formatted(classpathFile));

        String classpath = Files.readString(classpathFile, StandardCharsets.UTF_8).trim();
        Assertions.assertFalse(classpath.isBlank(), "Generated parser classpath must not be empty");
        Files.createDirectories(compiledClasses);
        compile(source, compiledClasses, classpath);

        List<URL> urls = new ArrayList<>();
        urls.add(compiledClasses.toUri().toURL());
        for (String entry : classpath.split(java.util.regex.Pattern.quote(File.pathSeparator))) {
            if (!entry.isBlank()) {
                urls.add(Path.of(entry).toUri().toURL());
            }
        }
        URLClassLoader loader = new URLClassLoader(
                urls.toArray(URL[]::new),
                ClassLoader.getPlatformClassLoader());
        Class<?> parser = Class.forName(PARSER_CLASS, true, loader);
        return new ProductionDocumentParserHarness(
                loader,
                parser.getMethod("parseDocument", byte[].class, String.class),
                parser.getMethod("isSupportedDocument", String.class));
    }

    static Path repositoryRoot() {
        Path current = Path.of(System.getProperty("user.dir")).toAbsolutePath().normalize();
        for (Path candidate = current; candidate != null; candidate = candidate.getParent()) {
            if (Files.isRegularFile(candidate.resolve("AGENTS.md"))
                    && Files.isDirectory(candidate.resolve("ai-service"))
                    && Files.isDirectory(candidate.resolve("document-service"))) {
                return candidate;
            }
        }
        throw new IllegalStateException("Unable to locate OmniDoc repository root from " + current);
    }

    String parse(byte[] content, String fileName) throws Exception {
        return (String) invoke(parseDocument, content, fileName);
    }

    boolean supports(String fileName) throws Exception {
        return (boolean) invoke(isSupportedDocument, fileName);
    }

    String readXlsxCellWithAvailablePoi(byte[] content, String sheetName, int rowIndex, int columnIndex)
            throws Exception {
        Class<?> workbookClass = Class.forName("org.apache.poi.xssf.usermodel.XSSFWorkbook", true, classLoader);
        Object workbook = workbookClass.getConstructor(InputStream.class)
                .newInstance(new ByteArrayInputStream(content));
        try {
            Object sheet = workbookClass.getMethod("getSheet", String.class).invoke(workbook, sheetName);
            Object row = sheet.getClass().getMethod("getRow", int.class).invoke(sheet, rowIndex);
            Object cell = row.getClass().getMethod("getCell", int.class).invoke(row, columnIndex);
            return cell.toString();
        } finally {
            workbookClass.getMethod("close").invoke(workbook);
        }
    }

    @Override
    public void close() throws Exception {
        classLoader.close();
    }

    private static void compile(Path source, Path output, String classpath) throws Exception {
        JavaCompiler compiler = ToolProvider.getSystemJavaCompiler();
        Assertions.assertNotNull(compiler, "M0-PB requires a JDK, not a JRE");
        DiagnosticCollector<JavaFileObject> diagnostics = new DiagnosticCollector<>();
        try (StandardJavaFileManager fileManager = compiler.getStandardFileManager(
                diagnostics, Locale.ROOT, StandardCharsets.UTF_8)) {
            Iterable<? extends JavaFileObject> units = fileManager.getJavaFileObjectsFromPaths(List.of(source));
            List<String> options = List.of(
                    "-classpath", classpath,
                    "-d", output.toString(),
                    "-encoding", "UTF-8",
                    "--release", "17");
            boolean success = compiler.getTask(null, fileManager, diagnostics, options, null, units).call();
            if (!success) {
                StringBuilder message = new StringBuilder("Could not compile production parser:\n");
                for (Diagnostic<? extends JavaFileObject> diagnostic : diagnostics.getDiagnostics()) {
                    message.append(diagnostic).append('\n');
                }
                Assertions.fail(message.toString());
            }
        }
    }

    private static Object invoke(Method method, Object... arguments) throws Exception {
        try {
            return method.invoke(null, arguments);
        } catch (InvocationTargetException exception) {
            Throwable cause = exception.getCause();
            if (cause instanceof Exception checked) {
                throw checked;
            }
            if (cause instanceof Error error) {
                throw error;
            }
            throw exception;
        }
    }
}
